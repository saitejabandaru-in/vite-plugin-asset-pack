import { build } from 'vite';
import { assetPackPlugin } from '../dist/index.mjs';
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function getDirSize(dirPath) {
  let size = 0;
  try {
    const files = await fs.readdir(dirPath);
    for (const file of files) {
      const filePath = path.join(dirPath, file);
      const stats = await fs.stat(filePath);
      if (stats.isFile()) {
        size += stats.size;
      }
    }
  } catch (e) {
    // ignore
  }
  return size;
}

async function runBenchmark() {
  console.log('🚀 Starting Automated Benchmark...');

  // Setup mock assets if they don't exist
  const assetsDir = path.join(__dirname, 'assets');
  await fs.mkdir(assetsDir, { recursive: true });
  
  // We'll use the example assets if local benchmarks/assets are empty
  const exampleAssets = path.join(__dirname, '../examples/vanilla/photo.jpg');
  try {
    await fs.copyFile(exampleAssets, path.join(assetsDir, 'test.jpg'));
  } catch (e) {
    // create a fake SVG
    await fs.writeFile(
      path.join(assetsDir, 'test.svg'),
      '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect x="10" y="10" width="80" height="80" fill="red"/></svg><!-- lots of comments --><!-- more comments -->'
    );
  }

  // Create a minimal Vite app entry point
  const srcDir = path.join(__dirname, 'src');
  await fs.mkdir(srcDir, { recursive: true });
  const entryPath = path.join(srcDir, 'index.js');
  
  // Read all assets and import them
  const assetFiles = await fs.readdir(assetsDir);
  let entryCode = '';
  for (const file of assetFiles) {
    entryCode += `import img_${file.replace(/[^a-zA-Z0-9]/g, '_')} from '../assets/${file}';\n`;
  }
  entryCode += 'console.log("Benchmark Entry");\n';
  await fs.writeFile(entryPath, entryCode);
  await fs.writeFile(path.join(__dirname, 'index.html'), '<script type="module" src="./src/index.js"></script>');

  const outDir = path.join(__dirname, 'dist');

  console.log('⏳ Running Vite Build...');
  const startTime = performance.now();

  await build({
    root: __dirname,
    build: {
      outDir,
      emptyOutDir: true,
      minify: false,
    },
    plugins: [
      assetPackPlugin({
        convertToAvif: true,
        cache: false // Disable cache for accurate benchmarking
      })
    ]
  });

  const endTime = performance.now();
  const buildTimeMs = (endTime - startTime).toFixed(2);

  const originalSize = await getDirSize(assetsDir);
  const optimizedSize = await getDirSize(path.join(outDir, 'assets'));
  
  const savedBytes = originalSize - optimizedSize;
  const savingsRatio = originalSize > 0 ? ((savedBytes / originalSize) * 100).toFixed(2) : '0.00';

  console.log('\n📊 Benchmark Results');
  console.log('---------------------');
  console.log(`⏱️ Build Time:      ${buildTimeMs} ms`);
  console.log(`📦 Original Size:   ${(originalSize / 1024).toFixed(2)} KB`);
  console.log(`📉 Optimized Size:  ${(optimizedSize / 1024).toFixed(2)} KB`);
  console.log(`🔥 Total Savings:   ${(savedBytes / 1024).toFixed(2)} KB (${savingsRatio}%)`);

  // Write report
  const report = `# Performance Benchmarks

*Auto-generated by \`benchmarks/run.mjs\`*

| Metric | Result |
| ------ | ------ |
| ⏱️ Build Time | **${buildTimeMs} ms** |
| 📦 Original Size | **${(originalSize / 1024).toFixed(2)} KB** |
| 📉 Optimized Size (AVIF) | **${(optimizedSize / 1024).toFixed(2)} KB** |
| 🔥 Compression Ratio | **${savingsRatio}%** |

*Note: These benchmarks are run automatically on every pull request to ensure zero performance regressions.*
`;

  await fs.writeFile(path.join(__dirname, 'BENCHMARKS.md'), report);
  console.log('✅ BENCHMARKS.md generated successfully!');
}

runBenchmark().catch(console.error);
